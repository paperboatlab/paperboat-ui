"""Write src/icons.ts from the icon registry (GUIDELINES §4 "One registry for icons").

Every icon of agent-docs/rebrand/icons.toml that is in use, free for its meaning or in conflict (not
retired) goes in: Codicons from rebrand/refs/codicons (classic v0.0.36), rail icons from
rebrand/apps/launcher/rail-icons.svg, our UI glyphs from logogen/src/system.jl BRAND_ICONS. An icon that isn't in the registry can't be drawn by <Icon>.
    python3 scripts/icons.py ~/Cloud/gdrive/Projects/paperboatlab/agent-docs/rebrand
"""
import json
import pathlib
import re
import sys
import tomllib

rebrand = pathlib.Path(sys.argv[1]).expanduser()
registry = tomllib.loads((rebrand / "icons.toml").read_text())["icon"]
rail = (rebrand / "apps" / "launcher" / "rail-icons.svg").read_text()
system = (rebrand / "logogen" / "src" / "system.jl").read_text()
brand_src = system[system.index("const BRAND_ICONS = Dict("):]
brand_src = brand_src[:brand_src.index("\nconst ")]
brand = dict(re.findall(r'"([\w-]+)" => "(<.*?)"(?=[,)])', brand_src))
# our formats' marks (logogen/src/system.jl mark_body), as drawn in this repo's ui-example.html (built by brand.jl)
example = (pathlib.Path(__file__).resolve().parent.parent / "ui-example.html").read_text()
def mark(app):
    if app == "paperboat":
        return "<path d='M8 2.5 3.5 9.5H8z'/><path d='M9.5 5.5 12.5 9.5H9.5z'/><path d='M2 11h12l-1.5 2.5h-9z'/>"
    m = re.search(rf"<svg class='fi fc-{app}'[^>]*viewBox='0 0 16 16' fill='none'[^>]*>(<rect x='2.5'.*?)</svg>", example)
    if not m:
        raise SystemExit(f"no mark for {app} in ui-example.html: rebuild it (julia logogen/src/brand.jl)")
    return m.group(1)
out, meaning = {}, {}
for i in registry:
    if i["status"] == "retired":  # a conflict keeps its registered meaning; its note names the misuse
        continue
    line = i["from"] in ("brand", "mark")  # our UI glyphs and marks: drawn as 1 px lines (.pb-icon.line)
    if i["from"] == "mark":
        box, body = "0 0 16 16", mark(i["id"].removeprefix("mark-"))
    elif line:
        box, body = "0 0 16 16", brand[i["id"]]
    elif i["from"] == "rail":
        m = re.search(rf'<symbol id="{i["id"]}" viewBox="([^"]+)">(.*?)</symbol>', rail, re.S)
        box, body = m.group(1), m.group(2)
    else:
        svg = (rebrand / "refs" / "codicons" / f'{i["id"]}.svg').read_text()
        b = re.search(r'viewBox="([^"]+)"', svg)
        box = b.group(1) if b else "0 0 16 16"
        body = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg, flags=re.S).strip()
    out[i["id"]] = [box, re.sub(r"\s+", " ", body), line]
    meaning[i["id"]] = i["meaning"]
lines = ["// Generated by scripts/icons.py from agent-docs/rebrand/icons.toml: do not edit. Codicons (classic v0.0.36,",
         "// CC BY 4.0, Microsoft), our rail icons (set A) and our UI glyphs (a third value: drawn as lines). Each icon has one meaning, everywhere.", "",
         "export const ICONS = {"]
for k, (box, body, line) in out.items():
    lines.append(f"  /** {meaning[k]} */")
    lines.append(f"  {json.dumps(k)}: [{json.dumps(box)}, {json.dumps(body)}{', true' if line else ''}],")
lines += ["} as const satisfies Record<string, readonly [string, string] | readonly [string, string, true]>;", "", "export type IconName = keyof typeof ICONS;", ""]
(pathlib.Path(__file__).resolve().parent.parent / "src" / "icons.ts").write_text("\n".join(lines))
print(f"src/icons.ts: {len(out)} icons")
